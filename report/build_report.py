def fig_path():
    labels = [label for _, label in PATH] + ["тест\n(финал)"]
    values = [EXP[key]["ALL"]["cer"] * 100 for key, _ in PATH] + [TEST["ALL"]["cer"] * 100]
    colors_ = [BLUE] * 4 + [ORANGE] * 4 + [GREEN]
    fig, ax = plt.subplots(figsize=(10, 4.2))
    positions = list(range(len(labels)))
    bars = ax.bar(positions, values, color=colors_)
    ax.set_xticks(positions, labels)
    for bar, value in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, value + 1, num(value), ha="center", fontsize=10)
    ax.axhline(30, color=RED, linestyle="-.", linewidth=1.2, label="порог ТЗ 30%")
    ax.yaxis.grid(True, color="#D9D9D9", linewidth=0.6)
    ax.set_axisbelow(True)
    ax.set_ylabel("CER по плавке и листу, %")
    ax.set_ylim(0, 95)
    ax.legend(loc="upper right", frameon=False)
    ax.spines[["top", "right", "left"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIGURES / "fig1_path.png", dpi=200)
    plt.close(fig)


