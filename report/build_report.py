def p(text, style=BODY):
    story.append(Paragraph(text, style))


first_section = [True]


def h1(text):
    if not first_section[0]:
        story.append(PageBreak())
    first_section[0] = False
    heading = Paragraph(text.upper(), H1)
    heading.toc_text = text
    story.append(heading)


def h2(text):
    story.append(CondPageBreak(4 * cm))
    story.append(Paragraph(text, H2))


def h3(text):
    story.append(CondPageBreak(3.5 * cm))
    story.append(Paragraph(text, H3))


def bullets(items, numbered=False):
    flow = ListFlowable(
        [ListItem(Paragraph(item, BODY_NOINDENT), leftIndent=14) for item in items],
        bulletType="1" if numbered else "bullet",
        bulletFormat="%s)" if numbered else None,
        start="1" if numbered else "–",
        leftIndent=1.0 * cm,
        bulletFontName="Times",
        bulletFontSize=14,
    )
    story.append(flow)


def table(caption, header, rows, widths):
    table_counter[0] += 1
    data = [[Paragraph(str(c), CELL_HEAD) for c in header]] + [[Paragraph(str(c), CELL) for c in row] for row in rows]
    t = Table(data, colWidths=[w * cm for w in widths], repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.4, colors.black),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DCE6F1")),
                ("VALIGN", (0, 0), (-1, 0), "MIDDLE"),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    caption_paragraph = Paragraph(f"Таблица {table_counter[0]} – {caption}", CAPTION_TABLE)
    if len(rows) <= 6:
        story.append(KeepTogether([caption_paragraph, t]))
    else:
        story.append(CondPageBreak(5 * cm))
        story.append(caption_paragraph)
        story.append(t)
    story.append(Spacer(1, 6))


